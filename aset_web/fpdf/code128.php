class PDF_Barcode extends FPDF {
    function Barcode128($x, $y, $code, $w, $h) {
        $Aarray = array(
            ' '=>'212222','!'=>'222122','"'=>'222221','#'=>'121223','$'=>'121322','%'=>'131222',
            '&'=>'122213','\''=>'122312','('=>'132212',')'=>'221213','*'=>'221312','+'=>'231212',
            ','=>'112232','-'=>'112331','.'=>'132113','/'=>'132311','0'=>'211313','1'=>'231113',
            '2'=>'231311','3'=>'112133','4'=>'112331','5'=>'132131','6'=>'113123','7'=>'113321',
            '8'=>'133121','9'=>'313121',':'=>'211331',';'=>'311123','<'=>'311321','='=>'331121',
            '>'=>'312113','?'=>'312311','@'=>'332111','A'=>'111431','B'=>'113411','C'=>'111233',
            'D'=>'111332','E'=>'113213','F'=>'113312','G'=>'111413','H'=>'113412','I'=>'113114',
            'J'=>'114113','K'=>'114311','L'=>'411113','M'=>'411311','N'=>'113141','O'=>'114131',
            'P'=>'311141','Q'=>'411131','R'=>'211412','S'=>'211214','T'=>'211412','U'=>'233111',
            'V'=>'211431','W'=>'241112','X'=>'131114','Y'=>'131411','Z'=>'122114','['=>'122411',
            '\\'=>'142112',']'=>'142411','^'=>'141122','_'=>'141221','`'=>'112214','a'=>'112412',
            'b'=>'122114','c'=>'122411','d'=>'142112','e'=>'142411','f'=>'141122','g'=>'141221',
            'h'=>'112241','i'=>'114221','j'=>'511111','k'=>'115111','l'=>'111511','m'=>'111151',
            'n'=>'111115','o'=>'511111','p'=>'115111','q'=>'111511','r'=>'111151','s'=>'111115',
            't'=>'121241','u'=>'124211','v'=>'411212','w'=>'421112','x'=>'421211','y'=>'212141',
            'z'=>'214121','{'=>'412112','|'=>'411221','}'=>'422111','~'=>'421121'
        );

        $code_upper = strtoupper($code);
        $seq = '211214'; 

        for ($i = 0; $i < strlen($code_upper); $i++) {
            $char = $code_upper[$i];
            if (isset($Aarray[$char])) {
                $seq .= $Aarray[$char];
            }
        }
        $seq .= '2331112'; 

        $total_units = 0;
        for ($i = 0; $i < strlen($seq); $i++) {
            $total_units += (int)$seq[$i];
        }
        $unit_width = $w / $total_units;

        $this->SetFillColor(0, 0, 0);
        $current_x = $x;
        for ($i = 0; $i < strlen($seq); $i++) {
            $bar_width = (int)$seq[$i] * $unit_width;
            if ($i % 2 == 0) {
                $this->Rect($current_x, $y, $bar_width, $h, 'F');
            }
            $current_x += $bar_width;
        }

        // Teks Kode di bawah Barcode
        $this->SetFont('Arial', '', 7);
        $this->SetXY($x, $y + $h + 1);
        $this->Cell($w, 3, $code, 0, 0, 'C');
    }
}
